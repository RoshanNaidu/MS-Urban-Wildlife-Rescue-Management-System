SELECT
  INCIDENT_ID,
  INCIDENT_DATE,
  INCIDENT_TYPE,
  INCIDENT_LOCATION,
  INCIDENT_STATUS
FROM INCIDENT
ORDER BY INCIDENT_DATE DESC;



SELECT
  A.ANIMAL_ID,
  S.SPECIES_COMMON_NAME,
  A.ANIMAL_HEALTH_STATUS,
  A.ANIMAL_INTAKE_DATE
FROM ANIMAL A
JOIN SPECIES S
  ON S.SPECIES_ID = A.SPECIES_ID
ORDER BY A.ANIMAL_ID;



SELECT
  AFA.ANIMAL_FACILITY_ASSIGNMENT_ID,
  AFA.ANIMAL_ID,
  F.FACILITY_NAME,
  (SELECT MAX(I.INVENTORY_LAST_UPDATED)
  FROM INVENTORY I
  WHERE I.ANIMAL_FACILITY_ASSIGNMENT_ID = AFA.ANIMAL_FACILITY_ASSIGNMENT_ID) AS LAST_INVENTORY_DATE
FROM ANIMAL_FACILITY_ASSIGNMENT AFA
JOIN FACILITY F
  ON F.FACILITY_ID = AFA.FACILITY_ID
ORDER BY AFA.ANIMAL_FACILITY_ASSIGNMENT_ID;